#!/usr/bin/env python3
"""Measure every gate arm and keep the generated metrics document in step.

``--measure`` runs each arm through ``./run.sh``, times it, and rewrites
``docs/_generated/gate-metrics.json`` plus the Markdown rendered from it.
``--check`` verifies that the Markdown still matches the JSON, that the JSON
covers exactly the measured arm set, and that the recorded test count still
matches the suite, so a hand-edited number or a new arm fails the docs gate.

Numbers in the generated document are never edited by hand; run
``./run.sh measure`` after a change that alters an arm.
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "docs" / "_generated" / "gate-metrics.json"
MARKDOWN_PATH = ROOT / "docs" / "_generated" / "gate-metrics.md"
SCHEMA = "aeos-gate-metrics/v1"

MEASURED_ARMS = (
    "setup",
    "validate",
    "build",
    "lint",
    "fast",
    "test",
    "docs",
    "gnn",
    "gnn-parser",
    "release",
    "render",
)
DECLARED_OTHER_ARMS = {"setup", "compat", "gate", "ci", "measure", "list", "help"}

COLLECTED = re.compile(r"(\d+) tests? collected")
COVERAGE = re.compile(r"Total coverage:\s*([\d.]+)%")


def fail(message: str, failures: list[str]) -> None:
    failures.append(message)


def runner_arms() -> list[str]:
    completed = subprocess.run(
        [str(ROOT / "run.sh"), "list"], capture_output=True, text=True, check=False
    )
    return [line.strip() for line in completed.stdout.splitlines() if line.strip()]


def collected_tests() -> int | None:
    completed = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", "--no-cov"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        return None
    per_file = sum(int(count) for count in re.findall(r":\s*(\d+)\s*$", completed.stdout, re.MULTILINE))
    if per_file:
        return per_file
    match = COLLECTED.search(completed.stdout)
    return int(match.group(1)) if match else None


def uv_version() -> str:
    completed = subprocess.run(["uv", "--version"], capture_output=True, text=True, check=False)
    return completed.stdout.strip().split()[1] if completed.returncode == 0 and completed.stdout else "unavailable"


def measure_arm(arm: str) -> dict[str, Any]:
    started = time.monotonic()
    completed = subprocess.run(
        [str(ROOT / "run.sh"), arm], cwd=ROOT, capture_output=True, text=True, check=False
    )
    seconds = round(time.monotonic() - started, 2)
    status = "passed" if completed.returncode == 0 else f"failed ({completed.returncode})"
    return {"name": arm, "seconds": seconds, "status": status, "output": completed.stdout}


def measure() -> dict[str, Any]:
    # The docs arm checks the generated document, so every other arm runs first
    # and the document is written before docs is measured.
    arms: list[dict[str, Any]] = []
    coverage: float | None = None
    for arm in (name for name in MEASURED_ARMS if name != "docs"):
        result = measure_arm(arm)
        output = result.pop("output")
        if arm == "test":
            match = COVERAGE.search(output)
            coverage = float(match.group(1)) if match else None
        arms.append(result)
    data: dict[str, Any] = {
        "schema": SCHEMA,
        "measured_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "host": {
            "platform": platform.platform(terse=True),
            "python": platform.python_version(),
            "uv": uv_version(),
        },
        "tests": {"collected": collected_tests(), "coverage_percent": coverage},
        "arms": arms,
    }
    provisional = {"name": "docs", "seconds": 0.0, "status": "pending"}
    data["arms"] = sorted(arms + [provisional], key=lambda entry: MEASURED_ARMS.index(entry["name"]))
    write(data)
    docs_result = measure_arm("docs")
    docs_result.pop("output")
    arms.append(docs_result)
    data["arms"] = sorted(arms, key=lambda entry: MEASURED_ARMS.index(entry["name"]))
    data["tests"]["collected"] = collected_tests()
    write(data)
    return data


def render_markdown(data: dict[str, Any]) -> str:
    host = data["host"]
    tests = data["tests"]
    coverage = tests["coverage_percent"]
    lines = [
        "# Gate metrics",
        "",
        "<!-- generated by scripts/gate_metrics.py; refresh with ./run.sh measure -->",
        "",
        "Measured wall time for every gate arm on one host. The numbers come from a",
        "single run of each arm through `./run.sh`; `./run.sh docs` fails when this",
        "file no longer matches `gate-metrics.json` or the recorded test count.",
        "",
        "| Fact | Value |",
        "| --- | --- |",
        f"| Collected tests | {tests['collected']} |",
        f"| Coverage | {'unavailable' if coverage is None else f'{coverage:.2f}%'} |",
        f"| Measured at | {data['measured_at']} |",
        f"| Host | {host['platform']} |",
        f"| Python | {host['python']} |",
        f"| uv | {host['uv']} |",
        "",
        "## Arm wall times",
        "",
        "| Arm | Command | Seconds | Result |",
        "| --- | --- | --- | --- |",
    ]
    for arm in data["arms"]:
        lines.append(f"| {arm['name']} | `./run.sh {arm['name']}` | {arm['seconds']:.2f} | {arm['status']} |")
    lines.append("")
    return "\n".join(lines)


def write(data: dict[str, Any]) -> None:
    MARKDOWN_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    MARKDOWN_PATH.write_text(render_markdown(data), encoding="utf-8")


def load() -> dict[str, Any] | None:
    try:
        data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def check(failures: list[str]) -> None:
    data = load()
    if data is None:
        fail(f"{JSON_PATH.relative_to(ROOT)} is missing or unreadable; run ./run.sh measure", failures)
        return
    if data.get("schema") != SCHEMA:
        fail(f"{JSON_PATH.relative_to(ROOT)} schema is not {SCHEMA}", failures)
    measured = [arm.get("name") for arm in data.get("arms", []) if isinstance(arm, dict)]
    if tuple(measured) != MEASURED_ARMS:
        fail("gate metrics do not cover exactly the measured arm set", failures)
    unmeasured = sorted(set(runner_arms()) - set(MEASURED_ARMS) - DECLARED_OTHER_ARMS)
    if unmeasured:
        fail(f"run.sh arms without a measurement: {', '.join(unmeasured)}", failures)
    expected = render_markdown(data)
    try:
        actual = MARKDOWN_PATH.read_text(encoding="utf-8")
    except OSError:
        actual = ""
    if actual != expected:
        fail(f"{MARKDOWN_PATH.relative_to(ROOT)} was edited by hand or is stale; run ./run.sh measure", failures)
    recorded = data.get("tests", {}).get("collected")
    live = collected_tests()
    if live is None:
        fail("the test suite could not be collected", failures)
    elif recorded != live:
        fail(f"recorded test count {recorded} does not match {live}; run ./run.sh measure", failures)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--measure", action="store_true", help="time every arm and rewrite the documents")
    group.add_argument("--check", action="store_true", help="verify the documents against the JSON and suite")
    args = parser.parse_args()

    if args.measure:
        data = measure()
        write(data)
        print(render_markdown(data))
        failed = [arm["name"] for arm in data["arms"] if arm["status"] != "passed"]
        if failed:
            print(f"FAIL: arms did not pass: {', '.join(failed)}", file=sys.stderr)
            return 1
        return 0
    if args.check:
        failures: list[str] = []
        check(failures)
        if failures:
            for failure in failures:
                print(f"FAIL: {failure}", file=sys.stderr)
            return 1
        print("Gate metrics are current.")
        return 0
    data = load()
    if data is None:
        print(f"FAIL: {JSON_PATH.relative_to(ROOT)} is missing; run ./run.sh measure", file=sys.stderr)
        return 1
    print(render_markdown(data), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

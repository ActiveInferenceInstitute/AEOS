#!/usr/bin/env python3
"""Measure gate arms and render one checked before/after record.

Use --measure for a fresh single sample per arm, --baseline for a saved
snapshot, and --output-dir for evidence outside the source tree. --record
publishes an already measured JSON snapshot without executing the arms again.
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "docs" / "_generated"
SCHEMA = "aeos-gate-metrics/v2"
MEASURED_ARMS = (
    "setup", "lock", "validate", "build", "lint", "fast", "test", "compat",
    "docs", "gnn", "gnn-parser", "release", "render", "gate", "ci", "default",
)
DECLARED_OTHER_ARMS = {"measure"}
COVERAGE = re.compile(r"Total coverage:\s*([\d.]+)%")


def collected_tests() -> int | None:
    completed = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", "--no-cov"],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )
    if completed.returncode != 0:
        return None
    counts = re.findall(r":\s*(\d+)\s*$", completed.stdout, re.MULTILINE)
    return sum(map(int, counts)) if counts else None


def command(arm: str) -> list[str]:
    return [str(ROOT / "run.sh")] + ([] if arm == "default" else [arm])


def measure_arm(arm: str) -> tuple[dict[str, Any], str]:
    started = time.monotonic()
    completed = subprocess.run(command(arm), cwd=ROOT, capture_output=True, text=True, check=False)
    row = {
        "name": arm, "seconds": round(time.monotonic() - started, 2),
        "status": "passed" if completed.returncode == 0 else f"failed ({completed.returncode})",
    }
    print(f"{arm}: {row['seconds']:.2f}s {row['status']}", file=sys.stderr)
    if completed.returncode:
        print(completed.stdout + completed.stderr, file=sys.stderr)
    return row, completed.stdout


def snapshot(arms: list[dict[str, Any]], coverage: float | None) -> dict[str, Any]:
    uv = subprocess.run(["uv", "--version"], capture_output=True, text=True, check=False)
    revision = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, stdin=subprocess.DEVNULL,
        capture_output=True, text=True, check=False,
    )
    return {
        "schema": SCHEMA, "measured_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "source_revision": revision.stdout.strip(),
        "host": {"platform": platform.platform(terse=True), "python": platform.python_version(), "uv": uv.stdout.strip()},
        "tests": {"collected": collected_tests(), "coverage_percent": coverage},
        "arms": sorted(arms, key=lambda arm: MEASURED_ARMS.index(arm["name"])),
    }


def validate(data: dict[str, Any]) -> None:
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise ValueError(f"metrics schema must be {SCHEMA}")
    if tuple(row["name"] for row in data["arms"]) != MEASURED_ARMS:
        raise ValueError("metrics must cover every measured arm exactly once, in order")
    for row in data["arms"]:
        if not isinstance(row["seconds"], (int, float)) or row["seconds"] < 0:
            raise ValueError(f"invalid duration for {row['name']}")
        if row["status"] != "passed" and not re.fullmatch(r"failed \(-?\d+\)", row["status"]):
            raise ValueError(f"invalid result for {row['name']}")
    if data.get("baseline") is not None:
        validate(data["baseline"])


def load(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    validate(data)
    return data


def render_markdown(data: dict[str, Any]) -> str:
    baseline = data.get("baseline")
    lines = [
        "# Gate metrics", "",
        "<!-- generated by scripts/gate_metrics.py; refresh with ./run.sh measure -->", "",
        "One wall-time sample per arm on this host, with existing environments (warm setup).",
        "Times include child startup and arm work, not the outer admission supervisor.",
        "These are observations, not a statistical speedup claim. Parser provisioning and",
        "exemplar retrieval require network; the other arms run offline.", "",
        "| Fact | Before | After |", "| --- | --- | --- |",
    ]
    for label, getter in (
        ("Measured at", lambda run: run["measured_at"]),
        ("Source HEAD (working-tree edits may be present)", lambda run: run["source_revision"]),
        ("Host", lambda run: run["host"]["platform"]),
        ("Python", lambda run: run["host"]["python"]),
        ("uv", lambda run: run["host"]["uv"]),
        ("Collected tests", lambda run: run["tests"]["collected"]),
        ("Coverage (%)", lambda run: run["tests"]["coverage_percent"]),
    ):
        lines.append(f"| {label} | {getter(baseline) if baseline else 'not recorded'} | {getter(data)} |")
    lines += ["", "## Arm wall times", "", "| Arm | Command | Before (s) | After (s) | Before / after result |", "| --- | --- | --- | --- | --- |"]
    before = {row["name"]: row for row in baseline["arms"]} if baseline else {}
    for row in data["arms"]:
        previous = before.get(row["name"])
        prior = f"{previous['seconds']:.2f}" if previous else "not recorded"
        status = previous["status"] if previous else "not recorded"
        invocation = "./run.sh" + ("" if row["name"] == "default" else " " + row["name"])
        lines.append(f"| {row['name']} | `{invocation}` | {prior} | {row['seconds']:.2f} | {status} / {row['status']} |")
    return "\n".join(lines) + "\n"


def write(data: dict[str, Any], directory: Path) -> None:
    validate(data)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "gate-metrics.json").write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (directory / "gate-metrics.md").write_text(render_markdown(data), encoding="utf-8")


def check() -> None:
    data = load(GENERATED / "gate-metrics.json")
    if (GENERATED / "gate-metrics.md").read_text(encoding="utf-8") != render_markdown(data):
        raise ValueError("generated Markdown differs from its JSON; run ./run.sh measure")
    if collected_tests() != data["tests"]["collected"] or data["tests"]["collected"] is None:
        raise ValueError("recorded test count differs from the suite; run ./run.sh measure")
    arms = subprocess.run([str(ROOT / "run.sh"), "list"], capture_output=True, text=True, check=True)
    if set(arms.stdout.split()) != (set(MEASURED_ARMS) - {"default"}) | DECLARED_OTHER_ARMS:
        raise ValueError("run.sh arm set differs from the measured arm set")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--measure", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--record", type=Path, help="render an already measured snapshot")
    parser.add_argument("--baseline", type=Path, help="retain a previous measurement snapshot")
    parser.add_argument("--output-dir", type=Path, default=GENERATED)
    args = parser.parse_args()
    try:
        if args.check:
            check()
            print("Gate metrics are current.")
            return 0
        if args.record:
            data = load(args.record)
        else:
            rows = []
            coverage = None
            for arm in MEASURED_ARMS:
                row, output = measure_arm(arm)
                rows.append(row)
                if arm == "test":
                    match = COVERAGE.search(output)
                    coverage = float(match.group(1)) if match else None
            data = snapshot(rows, coverage)
        if args.baseline:
            baseline = load(args.baseline)
            baseline.pop("baseline", None)
            data["baseline"] = baseline
        elif args.measure and (GENERATED / "gate-metrics.json").exists():
            previous = load(GENERATED / "gate-metrics.json")
            if previous.get("baseline") is not None:
                data["baseline"] = previous["baseline"]
        write(data, args.output_dir)
        print(render_markdown(data), end="")
        return int(any(row["status"] != "passed" for row in data["arms"]))
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
